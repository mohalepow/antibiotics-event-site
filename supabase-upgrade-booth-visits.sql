-- One-time booth visit tracking and dynamic booth achievement support.
-- Run after the core schema has created public.booths.
-- The public RPCs use the participant display name, matching the current profile system.

create table if not exists public.event_booth_visits (
  id bigint generated by default as identity primary key,
  player_key text not null,
  player_name text not null,
  booth_id text not null,
  visited_at timestamptz not null default now(),
  constraint event_booth_visits_player_booth_unique unique (player_key, booth_id)
);

create index if not exists event_booth_visits_booth_id_idx
  on public.event_booth_visits (booth_id);

alter table public.event_booth_visits enable row level security;
revoke all on table public.event_booth_visits from anon, authenticated;

create or replace function public.record_booth_visit(
  p_booth_id text,
  p_player_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_player_key text;
  v_booth_name text;
  v_inserted integer;
begin
  if p_booth_id is null or length(trim(p_booth_id)) = 0 then
    raise exception 'A booth ID is required';
  end if;

  if p_player_name is null or length(trim(p_player_name)) < 2 or length(trim(p_player_name)) > 18 then
    raise exception 'Player name must be between 2 and 18 characters';
  end if;

  select name into v_booth_name
  from public.booths
  where id::text = trim(p_booth_id)
  limit 1;

  if v_booth_name is null then
    raise exception 'Booth not found';
  end if;

  v_player_key := lower(trim(p_player_name));

  insert into public.event_booth_visits(player_key, player_name, booth_id)
  values (v_player_key, trim(p_player_name), trim(p_booth_id))
  on conflict (player_key, booth_id) do nothing;

  get diagnostics v_inserted = row_count;

  return jsonb_build_object(
    'already_visited', v_inserted = 0,
    'booth_name', v_booth_name
  );
end;
$$;

create or replace function public.get_visited_booths(p_player_name text)
returns table(booth_id text, visited_at timestamptz)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_player_name is null or length(trim(p_player_name)) < 2 or length(trim(p_player_name)) > 18 then
    return;
  end if;

  return query
  select v.booth_id, v.visited_at
  from public.event_booth_visits v
  where v.player_key = lower(trim(p_player_name))
  order by v.visited_at desc;
end;
$$;

revoke all on function public.record_booth_visit(text, text) from public;
revoke all on function public.get_visited_booths(text) from public;
grant execute on function public.record_booth_visit(text, text) to anon, authenticated;
grant execute on function public.get_visited_booths(text) to anon, authenticated;

comment on table public.event_booth_visits is
  'One-time participant booth visits; booth achievement titles are read dynamically from public.booths.name.';
